"""DAC-step pop with a DPCM return to centre, NTSC rate 7.

No recorded or game audio is used. Run from the repository root.
"""
import math
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

rate = 1789773 / 214
data = bytearray(33)  # 16 * 2 + 1 bytes, about 32 ms
level = 124  # Explicit DAC load at note-on: instantaneous attack, not a delta ramp.
for i in range(len(data) * 8):
    t = i / rate
    # A discontinuity from silence followed by a monotonic, short return.
    # The previous bipolar delta ramp softened the very attack we wanted.
    pulse = 60 * math.exp(-t / .0025)
    pulse *= min(1, max(0, (.025 - t) / .006))
    target = 64 + pulse
    bit = int(target >= level)
    if bit and level <= 125:
        level += 2
    elif not bit and level >= 2:
        level -= 2
    data[i // 8] |= bit << (i % 8)
(ROOT/'assets/kick.dmc').write_bytes(data)
(ROOT/'src/kick-data.h').write_text(
    '// Generated by scripts/make-kick.py. DAC-step pop.\n'
    '#define KICK_INITIAL_DAC 124\n'
    'static const unsigned char kick_data[] = {\n' +
    '\n'.join('    ' + ','.join(f'0x{x:02x}' for x in data[i:i+16]) + ','
              for i in range(0, len(data), 16)) + '\n};\n')
